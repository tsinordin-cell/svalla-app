export function arKommun(namn: string): boolean {
  return KOMMUNER.has(namn)
}

/** Rått namn från Nominatim → kort namn i versaler för väderrutan. */
export function kortOrtnamn(ratt: string): string {
  let namn = ratt.trim()
  const varKommun = /\s+(kommun|stad)$/i.test(namn)
  namn = namn.replace(/\s+(kommun|stad)$/i, '').replace(/\s+län$/i, '').trim()
  if (varKommun && !KOMMUNER.has(namn) && /s$/.test(namn)) {
    const utanS = namn.slice(0, -1)
    if (KOMMUNER.has(utanS)) namn = utanS
  }
  return namn.toUpperCase()
}
